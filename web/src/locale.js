export function chooseLocale(saved, browserLanguage) {
  if (saved === "zh-CN" || saved === "en") return saved;
  return browserLanguage?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale, entry, values = {}) {
  const message = typeof entry === "object" && entry !== null ? entry.message : entry;
  const replacements = typeof entry === "object" && entry !== null ? entry.values ?? values : values;
  const source = message ?? "";
  const template = locale === "en" && Object.hasOwn(english, source) ? english[source] : source;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : placeholder);
}

export function formatTime(locale, value) {
  if (!value) return translate(locale, "不过期");
  return new Intl.DateTimeFormat(locale, {
    month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit"
  }).format(new Date(value));
}
